const BASE = `${import.meta.env.BASE_URL}img/3d/`;
const pulisci = (e) => e.replace(/\uFE0F|\uFE0E/g, "");

/** URL dell'immagine 3D di un'emoji, oppure null se non c'è. */
export function emoji3d(e) {
  if (!e) return null;
  const k = EMOJI_3D[e] || EMOJI_3D[pulisci(e)];
  return k ? `${BASE}emoji/${k}.webp` : null;
}

/** Posa dei compagni: "festa" | "incoraggia" | "indica". */
export const posa3d = (id, posa) => `${BASE}pose/${id}_${posa}.webp`;
/** Sfondo dipinto di un mondo (id del mondo in data/mondi.js). */
export const sfondo3d = (mondo) => `${BASE}sfondi/${mondo}.webp`;
/** Premi, icone e oggetti del negozio. */
export const premio3d = (nome) => `${BASE}premi/${nome}.webp`;
